// Regenerates the settings search table and its differential cases from the TypeScript source:
//   cd apps/web && bun run ../../rust/crates/t3-client/tests/settings_search_oracle.ts
// Writes src/services/settings/search_items.rs and tests/settings_search_differential.rs.
import { writeFileSync } from "node:fs";
import {
  SETTINGS_SEARCH_ITEMS,
  filterAvailableSettingsSearchItems,
  searchSettings,
  movedSettingsPath,
  getSettingsSearchTargetScope,
} from "../../../../apps/web/src/components/settings/settingsSearch.ts";

const root = new URL("..", import.meta.url);
const str = (value: string) => JSON.stringify(value);
const FLAGS = [
  "desktopOnly",
  "macOnly",
  "windowsOnly",
  "releaseChannelOnly",
  "secretsFeatureOnly",
  "cloudOnly",
  "environmentOnly",
  "providerSettingsOnly",
  "localBackendManagementOnly",
  "localEnvironmentOnly",
  "primaryEnvironmentOnly",
  "wslAvailableOnly",
  "managedTunnelOnly",
  "peerLinksOnly",
  "fastWorktreeCheckoutOnly",
  "textGeneratorsOnly",
  "secondary",
  "requiresThreadAutoSettlement",
] as const;
const snake = (name: string) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const scopeVariant = (scope: string | undefined) =>
  scope === undefined
    ? "None"
    : `Some(SettingsSearchScope::${scope.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase())})`;

const items = (SETTINGS_SEARCH_ITEMS as ReadonlyArray<Record<string, unknown>>).map((item) => {
  const flags = FLAGS.filter((flag) => item[flag] === true)
    .map((flag) => `${snake(flag)}: true, `)
    .join("");
  const terms = ((item.searchTerms as string[] | undefined) ?? []).map(str).join(", ");
  return `    SettingsSearchItem { id: ${str(item.id as string)}, title: ${str(item.title as string)}, to: ${str(item.to as string)}, target_id: ${item.targetId === undefined ? "None" : `Some(${str(item.targetId as string)})`}, search_terms: &[${terms}], scope: ${scopeVariant(item.scope as string | undefined)}, ${flags}..SettingsSearchItem::BASE },`;
});
writeFileSync(
  new URL("src/services/settings/search_items.rs", root),
  `//! Generated by tests/settings_search_oracle.ts from apps/web/src/components/settings/settingsSearch.ts
//! \`SETTINGS_SEARCH_ITEMS\`, in source order (search ranks ties by this order). Do not edit.
use super::search::{SettingsSearchItem, SettingsSearchScope};

pub static SETTINGS_SEARCH_ITEMS: &[SettingsSearchItem] = &[
${items.join("\n")}
];
`,
);

const everything = filterAvailableSettingsSearchItems({
  hasCloudPublicConfig: true,
  hasEnvironment: true,
  hasProviderSettingsEnvironment: true,
  canManageLocalBackend: true,
  isWslSettingsRowVisible: true,
  hasThreadAutoSettlement: true,
  managedTunnelActive: true,
  hasPeerLinkHost: true,
  hasFastWorktreeCheckoutEnvironment: true,
  hasTextGeneratorsEnvironment: true,
  hasPrimaryEnvironment: true,
});
const sparse = filterAvailableSettingsSearchItems({
  hasCloudPublicConfig: false,
  hasEnvironment: false,
  hasProviderSettingsEnvironment: false,
  canManageLocalBackend: false,
  isWslSettingsRowVisible: false,
  hasThreadAutoSettlement: false,
});
const queries = [
  "theme",
  "Theme",
  "  font   size ",
  "delete",
  "confirm",
  "auto settle",
  "keybinding",
  "mod+k",
  "github",
  "worktree",
  "resume",
  "café",
  "notifications",
  "language",
  "zzz-no-match",
  "general",
  "send",
];
const cases = queries.map((query) => ({
  query,
  all: searchSettings(query, everything).map((item) => item.id),
  sparse: searchSettings(query, sparse).map((item) => item.id),
}));
const moved = [
  ["/settings/general", "authorized-clients"],
  ["/settings/general", "text-generation"],
  ["/settings/general", ""],
  ["/settings/integrations", ""],
  ["/settings/storage", "storage-worktrees"],
  ["/settings/appearance", "theme"],
  ["/settings/general", "language"],
  ["/settings/threads", "text-generation"],
].map(([path, hash]) => ({ path, hash, to: movedSettingsPath(path!, hash!) }));
const scopes = ["storage-worktrees", "language", "authorized-clients", "nope"].map((id) => ({
  id,
  scope: getSettingsSearchTargetScope(id),
}));
const rows = cases
  .map(
    (c) =>
      `    (${str(c.query)}, &[${c.all.map(str).join(", ")}], &[${c.sparse.map(str).join(", ")}]),`,
  )
  .join("\n");
const movedRows = moved
  .map((m) => `    (${str(m.path!)}, ${str(m.hash!)}, ${m.to === null ? "None" : `Some(${str(m.to)})`}),`)
  .join("\n");
const scopeRows = scopes
  .map(
    (s) =>
      `    (${str(s.id)}, ${s.scope === null ? "None" : `Some((${str(s.scope.title)}, ${s.scope.scope === null ? "None" : `Some(${str(s.scope.scope)})`}))`}),`,
  )
  .join("\n");
writeFileSync(
  new URL("tests/settings_search_differential.rs", root),
  `//! Generated by tests/settings_search_oracle.ts: results of the TypeScript settings search on a
//! non-desktop, non-Mac, non-Windows platform. Do not edit.
use t3_client::services::settings::search::{
    SettingsSearchAvailability, SettingsSearchPlatform, filter_available_settings_search_items,
    get_settings_search_target_scope, moved_settings_path, search_settings,
};

const CASES: &[(&str, &[&str], &[&str])] = &[
${rows}
];
const MOVED: &[(&str, &str, Option<&str>)] = &[
${movedRows}
];
const SCOPES: &[(&str, Option<(&str, Option<&str>)>)] = &[
${scopeRows}
];

#[test]
fn search_matches_typescript() {
    let everything = filter_available_settings_search_items(&SettingsSearchAvailability::everything());
    let sparse = filter_available_settings_search_items(&SettingsSearchAvailability::default());
    let platform = SettingsSearchPlatform::default();
    for (query, all, few) in CASES {
        let ids = |items: &[&t3_client::services::settings::search::SettingsSearchItem]| {
            search_settings(query, items, platform, |text| text.to_owned())
                .into_iter()
                .map(|item| item.id)
                .collect::<Vec<_>>()
        };
        assert_eq!(ids(&everything), *all, "{query}");
        assert_eq!(ids(&sparse), *few, "{query}");
    }
}

#[test]
fn moved_paths_and_target_scopes_match_typescript() {
    for (path, hash, to) in MOVED {
        assert_eq!(moved_settings_path(path, hash), *to, "{path}#{hash}");
    }
    for (id, expected) in SCOPES {
        let scope = get_settings_search_target_scope(id)
            .map(|scope| (scope.title, scope.scope.map(|scope| scope.as_str())));
        assert_eq!(scope, *expected, "{id}");
    }
}
`,
);
console.log(`items ${items.length}, cases ${cases.length}`);
