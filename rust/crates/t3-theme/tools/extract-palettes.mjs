// Emits fixtures/palettes.json (built-in themes, standard colours, role table, ids) from
// packages/shared/src/themePalettes.ts and src/palette/roles.rs from the same role list.
// With --check, fails if either checked-in file differs.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { spawnSync } from "node:child_process";
import { crateDir, repoRoot } from "./lib.mjs";

const shared = await import(pathToFileURL(join(repoRoot, "packages/shared/src/themePalettes.ts")).href);
const palette = await import(pathToFileURL(join(repoRoot, "apps/web/src/themePalette.ts")).href);
const chips = await import(pathToFileURL(join(repoRoot, "apps/web/src/lib/contextChipAccents.ts")).href);

const roles = shared.THEME_COLOR_ROLES;
const upper = (s) => s[0].toUpperCase() + s.slice(1);

const fixture = {
  roles: roles.map((name) => ({ name, cssVariable: palette.getThemeColorVariable(name) })),
  builtInThemeIds: [...shared.BUILT_IN_THEME_IDS],
  mobileDefaultThemeId: shared.MOBILE_DEFAULT_THEME_ID,
  mobileThemeIds: [...shared.MOBILE_THEME_IDS],
  reservedThemeIds: [...shared.RESERVED_THEME_IDS],
  unpublishableThemeIds: [...shared.UNPUBLISHABLE_THEME_IDS],
  builtInThemes: shared.BUILT_IN_THEMES,
  t3CodeLightColors: shared.T3_CODE_LIGHT_THEME_COLORS,
  t3CodeDarkColors: shared.T3_CODE_DARK_THEME_COLORS,
  contextChipAccents: Object.entries(chips.CONTEXT_CHIP_ACCENTS).map(([kind, accent]) => ({
    kind,
    accent,
    cssVariable: chips.contextChipColorVariable(kind),
  })),
};
const json = `${JSON.stringify(fixture, null, 1)}\n`;

let rs = "//! Theme colour roles (generated by tools/extract-palettes.mjs from packages/shared; do not edit).\n\n";
rs += `pub const ROLE_COUNT: usize = ${roles.length};\n\n`;
rs += "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\npub enum ThemeColorRole {\n";
for (const r of roles) rs += `    ${upper(r)},\n`;
rs += "}\n\nimpl ThemeColorRole {\n    pub const ALL: [ThemeColorRole; ROLE_COUNT] = [\n";
for (const r of roles) rs += `        ThemeColorRole::${upper(r)},\n`;
rs += "    ];\n\n    /// The camelCase key used in theme files.\n    pub const fn name(self) -> &'static str {\n        match self {\n";
for (const r of roles) rs += `            ThemeColorRole::${upper(r)} => "${r}",\n`;
rs += "        }\n    }\n\n    /// The `--app-theme-*` custom property that carries this role.\n    pub const fn css_variable(self) -> &'static str {\n        match self {\n";
for (const r of roles) rs += `            ThemeColorRole::${upper(r)} => "${palette.getThemeColorVariable(r)}",\n`;
rs += "        }\n    }\n}\n";

// The checked-in file is rustfmt-formatted, so compare and write the formatted text.
const formatted = spawnSync("rustfmt", ["--edition", "2024", "--emit", "stdout"], { input: rs, encoding: "utf8" });
if (formatted.status === 0) rs = formatted.stdout;
const targets = [
  [join(crateDir, "fixtures/palettes.json"), json],
  [join(crateDir, "src/palette/roles.rs"), rs],
];
if (process.argv.includes("--check")) {
  let bad = false;
  for (const [path, text] of targets) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== text) {
      console.error(`stale: ${path}`);
      bad = true;
    }
  }
  process.exit(bad ? 1 : 0);
}
for (const [path, text] of targets) writeFileSync(path, text);
console.log("roles", roles.length, "themes", fixture.builtInThemes.length);
