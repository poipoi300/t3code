// Emits src/color/named.rs from culori's CSS named-colour table.
import { pathToFileURL } from "node:url";
import { writeFileSync } from "node:fs";
const root = process.argv[2];
const named = (await import(pathToFileURL(`${root}/node_modules/.pnpm/culori@4.0.2/node_modules/culori/src/colors/named.js`).href)).default;
const rows = Object.entries(named).sort(([a], [b]) => a.localeCompare(b));
let out = "//! CSS named colours (generated by tools/gen-named.mjs from culori; do not edit).\n\npub const NAMED: &[(&str, u32)] = &[\n";
for (const [n, v] of rows) out += `    ("${n}", 0x${v.toString(16).padStart(6, "0")}),\n`;
out += "];\n";
writeFileSync(process.argv[3], out);
console.log(rows.length);
