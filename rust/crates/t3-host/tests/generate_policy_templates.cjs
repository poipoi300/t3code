const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const {stripTypeScriptTypes} = require("node:module");
const repo = path.resolve(__dirname,"../../../..");
const read = relative => fs.readFileSync(path.join(repo,relative),"utf8");
const source = read("apps/server/src/policy/policyTemplates.ts");
const providers = read("apps/server/src/policy/managedProviders.ts");
const imports = [...providers.matchAll(/import \{ (\w+) \} from "@t3tools\/(provider-[^/]+)\/client";/g)];
const clients = new Map(imports.map(([,name,pkg]) => {
  const client = read(`packages/${pkg}/src/client.ts`);
  const driver = client.match(/driverKind:\s*(?:ProviderDriverKind\.make\()?"([^"]+)"/);
  const label = client.match(/label:\s*"([^"]+)"/);
  if (!driver || !label) throw new Error(`Cannot extract driver label: ${pkg}`);
  return [name,{driver:driver[1],label:label[1]}];
}));
const packaged = providers.match(/const PACKAGED_CLIENTS[^=]*= \[([\s\S]*?)\];/)[1].match(/\w+Client/g).map(name => clients.get(name));
if (packaged.some(value => !value)) throw new Error("Missing packaged provider");
const labels = [...providers.matchAll(/known\("([^"]+)", "([^"]+)"/g)].map(([,driver,label]) => ({driver,label})).concat(packaged);
const registry = read("packages/shared/src/managedPolicyFile.ts");
const subkey = registry.match(/const WINDOWS_POLICY_SUBKEY = ([^;]+);/)[1];
const definitions = registry.slice(registry.indexOf("export const WINDOWS_POLICY_VALUES"),registry.indexOf("// An absolute path:"));
const body = source.replace(/^import[\s\S]*?;\r?\n/gm,"").replaceAll("export function ","function ");
const code = `const WINDOWS_POLICY_KEY = "HKLM\\\\" + ${subkey};\n${definitions.replaceAll("export const ","const ")}\n${body}\nglobalThis.render={windowsAdmx,windowsAdml,macosProfile};`;
const context = vm.createContext({knownDriverLabels:() => labels});
vm.runInContext(stripTypeScriptTypes(code,{mode:"strip"}),context);
fs.writeFileSync(path.join(__dirname,"../src/policy-windows.admx"),context.render.windowsAdmx());
fs.writeFileSync(path.join(__dirname,"../src/policy-windows.adml"),context.render.windowsAdml());
const document = {schemaVersion:1,organization:"Org & Company",settings:{keepAwakeWhileAgentsWork:{value:false,locked:true}}};
const profile = context.render.macosProfile(document,{profile:"profile-uuid",payload:"payload-uuid"});
fs.writeFileSync(path.join(__dirname,"policy-profile.json"),JSON.stringify({document,profile:profile.profile},null,2)+"\n");
