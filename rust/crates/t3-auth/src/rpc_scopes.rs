use super::Scope;
macro_rules! rpc_scopes {
    ($($method:literal => $scope:ident),* $(,)?) => {
        pub const RPC_REQUIRED_SCOPES: &[(&str, Scope)] = &[$(($method, Scope::$scope)),*];
        pub(super) fn required_scope(method: &str) -> Option<Scope> {
            match method { $($method => Some(Scope::$scope),)* _ => None }
        }
    };
}
